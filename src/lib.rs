//! `libqb` — Rust port of the ClusterLabs libqb library.
//!
//! # Crate layout
//!
//! | Module | Contents |
//! |---|---|
//! | `atomic` | Atomic int/pointer operations (`qb_atomic_*`) |
//! | `list` | Intrusive circular doubly-linked list (`qb_list_*`) |
//! | `array` | Stable-pointer segmented array (`qb_array_*`) |
//! | `map` | Unified string-keyed map — hashtable / skiplist / trie |
//! | `hdb` | Handle database with reference counting |
//! | `util` | Locks, high-resolution time, stopwatch |
//! | `ringbuffer` | Shared-memory ring buffer (`qb_rb_*`) |
//! | `event_loop` | fd poll, one-shot timers, jobs, signal handlers |
//! | `ipc` | IPC wire types |
//! | `ipc_client` | IPC client (`qb_ipcc_*`) |
//! | `ipc_server` | IPC server (`qb_ipcs_*`) |
//! | `log` | Multi-target logging (`qb_log_*`) |
//!
//! # C compatibility
//!
//! Every `pub extern "C"` function in this crate is exported with `#[no_mangle]`.
//! Run `cargo build` and use `include/qb.h` (generated by cbindgen) to link
//! from C or C++ code.
//!
//! # Safety
//!
//! The C API requires raw pointers.  All `unsafe extern "C"` functions document
//! their safety invariants.  Rust callers should prefer the safe wrappers
//! exposed by each module.

