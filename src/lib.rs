/// Convenience macro for logging from Rust code.
///
/// ```rust,no_run
/// use libqb::qb_log;
/// qb_log!(libc::LOG_INFO as u8, "connection count: {}", count);
/// ```
#[macro_export]
macro_rules! qb_log {
    ($priority:expr, $fmt:literal $(, $arg:expr)* $(,)?) => {{
        use std::ffi::CString;
        use std::time::SystemTime;
        let msg = format!($fmt $(, $arg)*);
        let func = concat!(module_path!(), "\0");
        let file = concat!(file!(), "\0");
        let fmt_s = concat!($fmt, "\0");
        if let Ok(msg_c) = CString::new(msg) {
            unsafe {
                let cs = $crate::log::qb_log_callsite_get2(
                    std::ptr::null(),
                    func.as_ptr() as *const libc::c_char,
                    file.as_ptr() as *const libc::c_char,
                    fmt_s.as_ptr() as *const libc::c_char,
                    $priority,
                    line!(),
                    0,
                );
                if !cs.is_null() && (*cs).targets != 0 {
                    let mut ts = libc::timespec { tv_sec: 0, tv_nsec: 0 };
                    libc::clock_gettime(libc::CLOCK_REALTIME, &mut ts);
                    $crate::log::qb_log_dispatch_raw(cs, &ts, msg_c.as_ptr());
                }
            }
        }
    }};
}

